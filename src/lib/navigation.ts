/**
 * Перемещение по подземелью.
 *
 * Подземелье линейно: `POST /state/rooms` открывает комнату `номер + 1`,
 * а вернуться в пройденную можно через `PUT /state/rooms/current`.
 *
 * **Карта для возврата не нужна.** Предмет «КАРТА» требуется только для
 * `GET /state/map` — списка комнат с именами. Сам переход проверяет лишь
 * открытость комнаты, поэтому без карты игрок идёт назад по одной комнате,
 * а с картой прыгает сразу в любую.
 *
 * Стартовая комната (номер 0) открытой не становится никогда: `SaveFactory`
 * просто ставит `CurrentRoomId = 0`, а `Discover()` вызывает только переход
 * вперёд, и уже для новой комнаты. Поэтому `PUT` в комнату 0 всегда отвечает
 * `403 UNDISCOVERED_ROOM_ERROR`, и назад можно идти начиная с комнаты 2.
 * Потери в этом нет: содержимое генерируется только для комнат после
 * стартовой, сама она пустая.
 */
export function canGoBack(roomNumber: number): boolean {
  return roomNumber > 1
}
